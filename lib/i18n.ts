export const MESSAGES: Record<Locale, Messages> = { fr, 'en-GB': enGB, 'en-US': enUS, es, pt, it };

export function resolveLocale(value?: string | null): Locale {
  if (!value) return 'fr';
  const requested = value.split(',').map((part) => part.trim().split(';')[0]);
  for (const candidate of requested) {
    const exact = SUPPORTED_LOCALES.find((locale) => locale.toLowerCase() === candidate.toLowerCase());
    if (exact) return exact;
    const language = candidate.toLowerCase().split('-')[0];
    if (language === 'en') return candidate.toLowerCase().includes('us') ? 'en-US' : 'en-GB';
    const base = SUPPORTED_LOCALES.find((locale) => locale.toLowerCase() === language);
    if (base) return base;
  }
  return 'fr';
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {},
) {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    MESSAGES[locale][key] ?? MESSAGES.fr[key],
  );
}
